export function translate(language: string | undefined, key: I18nKey): string {
  const dict = I18N[(language || 'en') as LanguageCode] || EN;
  return dict[key] || EN[key];
}

/** `{{ 'dashboard' | t }}` — follows the applied (saved) language, updating as soon as it changes. */
@Pipe({ name: 't', standalone: true, pure: false })
export class TranslatePipe implements PipeTransform {
  private appearance = inject(AppearanceService);

  transform(key: I18nKey): string {
    return translate(this.appearance.state.display.language, key);
  }
}
